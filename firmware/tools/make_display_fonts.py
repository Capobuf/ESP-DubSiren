"""Generate the display's Adafruit GFX fonts from Teko SemiBold.

Same GFXfont layout as Adafruit's fontconvert: printable ASCII 0x20-0x7E,
one bit per pixel, rows packed MSB first, each glyph starting on a byte.
Glyphs are rendered by FreeType through Pillow, unhinted shapes thresholded
to one bit, as the display has no antialiasing.

    python firmware/tools/make_display_fonts.py

Requires Pillow. Writes firmware/src/display/fonts/TekoSemiBold<size>px.h.
"""

import hashlib
import tempfile
import urllib.request
from pathlib import Path

from PIL import ImageFont

# google/fonts at a fixed commit: Teko variable font, SIL OFL 1.1.
SOURCE = ("https://raw.githubusercontent.com/google/fonts/"
          "5a4e6a81aad60ed70e591092ffac7fb30cfa4cfb/ofl/teko/Teko%5Bwght%5D.ttf")
SHA256 = "d1321889f262bbbff632e7976349853399cd097b6f382d4b19790c915c13c1ae"
INSTANCE = "SemiBold"
# Pixel sizes; cap heights 10, 14, 21 and 26 px.
SIZES = (16, 22, 32, 40)
FIRST, LAST = 0x20, 0x7E

OUTPUT = Path(__file__).resolve().parents[1] / "src" / "display" / "fonts"


def fetch() -> bytes:
    with urllib.request.urlopen(SOURCE) as response:
        data = response.read()
    digest = hashlib.sha256(data).hexdigest()
    if digest != SHA256:
        raise SystemExit(f"unexpected Teko download: sha256 {digest}")
    return data


def glyph(font: ImageFont.FreeTypeFont, character: str):
    mask, (left, top) = font.getmask2(character, mode="1", anchor="ls")
    width, height = mask.size
    pixels = [[mask.getpixel((x, y)) != 0 for x in range(width)] for y in range(height)]
    advance = round(font.getlength(character))
    rows = [y for y in range(height) if any(pixels[y])]
    columns = [x for x in range(width) if any(pixels[y][x] for y in range(height))]
    if not rows:
        return [], 0, 0, advance, 0, 0
    x0, x1, y0, y1 = columns[0], columns[-1], rows[0], rows[-1]
    bits = [pixels[y][x] for y in range(y0, y1 + 1) for x in range(x0, x1 + 1)]
    data = []
    for start in range(0, len(bits), 8):
        byte = 0
        for index, bit in enumerate(bits[start:start + 8]):
            if bit:
                byte |= 0x80 >> index
        data.append(byte)
    return data, x1 - x0 + 1, y1 - y0 + 1, advance, left + x0, top + y0


def write(path: Path, size: int) -> None:
    font = ImageFont.truetype(str(path), size)
    font.set_variation_by_name(INSTANCE)
    ascent, descent = font.getmetrics()
    name = f"TekoSemiBold{size}px"
    bitmap, glyphs = [], []
    for code in range(FIRST, LAST + 1):
        data, width, height, advance, x_offset, y_offset = glyph(font, chr(code))
        glyphs.append((len(bitmap), width, height, advance, x_offset, y_offset, code))
        bitmap.extend(data)

    lines = [
        "// Generated by firmware/tools/make_display_fonts.py: do not edit.",
        f"// Teko {INSTANCE}, {size} px. Copyright 2023 The Teko Project Authors,",
        "// SIL Open Font License 1.1 (Teko-OFL.txt).",
        "#pragma once",
        "",
        "#include <Adafruit_GFX.h>",
        "",
        f"const uint8_t {name}Bitmaps[] PROGMEM = {{",
    ]
    for start in range(0, len(bitmap), 12):
        lines.append("    " + ", ".join(f"0x{b:02X}" for b in bitmap[start:start + 12]) + ",")
    lines += ["};", "", f"const GFXglyph {name}Glyphs[] PROGMEM = {{"]
    for offset, width, height, advance, x_offset, y_offset, code in glyphs:
        shown = "' '" if code == 0x20 else repr(chr(code))
        lines.append(f"    {{{offset}, {width}, {height}, {advance}, {x_offset}, {y_offset}}},"
                     f" // 0x{code:02X} {shown}")
    lines += [
        "};",
        "",
        f"const GFXfont {name} PROGMEM = {{(uint8_t *){name}Bitmaps,",
        f"    (GFXglyph *){name}Glyphs, 0x{FIRST:02X}, 0x{LAST:02X}, {ascent + descent}}};",
        "",
    ]
    (OUTPUT / f"{name}.h").write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print(f"{name}: {len(bitmap)} bytes of bitmap")


def main() -> None:
    OUTPUT.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory() as directory:
        path = Path(directory) / "Teko.ttf"
        path.write_bytes(fetch())
        for size in SIZES:
            write(path, size)


if __name__ == "__main__":
    main()
